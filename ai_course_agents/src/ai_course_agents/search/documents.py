"""Тексты-описания мест для семантического поиска.

Каждое место базы превращается в короткий текст, который потом переводится в вектор
(эмбеддинг). Запрос пользователя тоже переводится в вектор, и ближайшие по смыслу
тексты — это ответ поиска. Значит, место найдётся только по тому, что написано в его тексте.

Из чего собирается текст (всё по-русски, без адреса):
  «Ресторан «Марьяж». Кухня: русская кухня: пельмени, борщ…. Предположительно: …»
  • вид места по-русски («ресторан», «кафе, кофейня») — из poi/kinds.py;
  • название и бренд — как в базе;
  • кухня — тег cuisine через словарь search/cuisine.py (факт из базы);
  • догадка LLM по названию (search/enrich.py) — только для общепита без кухни,
    с пометкой «предположительно», чтобы и в тексте было видно, что это не факт.

Адрес в текст НЕ кладём: «пельмени на Садовой» — это смысл («пельмени») плюс место
(«Садовая»). Место ищется геофильтром по координатам, а не похожестью слов; иначе
запрос «пельмени» поднимал бы выше всё, что стоит на улицах с «вкусными» названиями.
"""

from __future__ import annotations

from typing import Any

from ai_course_agents.poi.kinds import KIND_LABELS
from ai_course_agents.search.cuisine import cuisine_words


def describe(place: dict[str, Any], guess: str | None = None) -> str:
    """Текст для эмбеддинга одного места. place — строка таблицы poi (dict)."""
    # Вид по-русски; для редких видов, которых нет в справочнике, — тег с пробелами.
    # Берём только ПЕРВОЕ название до запятой: «фастфуд, шаурма, бургерная» → «фастфуд».
    # Синонимы в KIND_LABELS нужны модели-агенту, но в описании они вредят: слово «шаурма»
    # оказалось бы у всех 161 фастфуда, и запрос «шаурма» не отличал бы шаурмичную от
    # бургерной (так и было в первой оценке — см. docs/PLAN.md).
    label = KIND_LABELS.get(place["kind"], place["kind"].replace("_", " "))
    kind = label.split(",")[0].strip()
    parts = [f"{kind.capitalize()} «{place['name']}»" if place.get("name") else kind.capitalize()]
    # Бренд добавляем, только если он не повторяет название («Магнит» «Магнит»).
    if place.get("brand") and place["brand"] != place.get("name"):
        parts.append(f"сеть {place['brand']}")
    if words := cuisine_words(place.get("cuisine")):
        parts.append(f"кухня: {words}")
    if guess:
        parts.append(f"предположительно: {guess}")
    return ". ".join(parts)     # части через точку — так модель видит их как отдельные утверждения
